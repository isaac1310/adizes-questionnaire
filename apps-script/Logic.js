if (typeof module !== "undefined") {
  module.exports = { TYPES: TYPES, BANDS: BANDS, isValidAnswers: isValidAnswers, scoreAnswers: scoreAnswers,
    bandOf: bandOf, codeOf: codeOf, cleanName: cleanName, sheetSafe: sheetSafe, isValidWorkshopCode: isValidWorkshopCode,
    newWorkshopCode: newWorkshopCode, suspicionFlags: suspicionFlags, validateSubmission: validateSubmission,
    MAX_ROWS_PER_WORKSHOP: MAX_ROWS_PER_WORKSHOP, isWellFormedKey: isWellFormedKey, keysMatch: keysMatch,
    cleanRoster: cleanRoster, submissionFromRow: submissionFromRow, MAX_ROSTER: MAX_ROSTER };
}
