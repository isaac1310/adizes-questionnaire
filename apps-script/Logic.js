/**
 * Pure logic, no Google services: validation, scoring, name safety.
 * Apps Script loads every .js file into one global scope, so these functions are
 * available to Code.js. The same file is loaded by test/logic.test.js under Node.
 *
 * Scoring and bands must match website/index.html (the site shows the same numbers).
 */

var TYPES = ["P", "A", "E", "I"];
var POINTS = [8, 4, 2, 1];
var QUESTION_COUNT = 20;
var NAME_MIN = 2, NAME_MAX = 40;
var MAX_ROWS_PER_WORKSHOP = 300;      // far above 50 participants; stops junk floods
var MIN_SECONDS_PLAUSIBLE = 120;      // faster than this gets a "suspicious" flag

// From Shlomo's results key "ריכוז תוצאות": lowest score of [משני, עיקרי, עיקרי מאוד]
var BANDS = { P: [68, 82, 90], A: [83, 97, 105], E: [73, 87, 95], I: [48, 62, 70] };

/** answers: 20 rows, each a ranking of type indices (0=P 1=A 2=E 3=I), best first. */
function isValidAnswers(answers) {
  if (!Array.isArray(answers) || answers.length !== QUESTION_COUNT) return false;
  for (var i = 0; i < answers.length; i++) {
    var row = answers[i];
    if (!Array.isArray(row) || row.length !== 4) return false;
    var seen = {};
    for (var j = 0; j < 4; j++) {
      var t = row[j];
      if (typeof t !== "number" || t !== Math.floor(t) || t < 0 || t > 3 || seen[t]) return false;
      seen[t] = true;
    }
  }
  return true;
}

function scoreAnswers(answers) {
  var s = { P: 0, A: 0, E: 0, I: 0 };
  answers.forEach(function (row) { row.forEach(function (t, rank) { s[TYPES[t]] += POINTS[rank]; }); });
  return s;
}

function bandOf(type, value) {
  return BANDS[type].filter(function (min) { return value >= min; }).length;   // 0..3
}

/** capital = עיקרי / עיקרי מאוד, small = משני, dash = פחות מועדף */
function codeOf(s) {
  return TYPES.map(function (t) {
    var b = bandOf(t, s[t]);
    return b >= 2 ? t : b === 1 ? t.toLowerCase() : "-";
  }).join("");
}

/** Trim, collapse spaces, strip control characters; null if not a usable name. */
function cleanName(raw) {
  if (typeof raw !== "string") return null;
  var n = raw.replace(/[\u0000-\u001F\u007F]/g, " ").replace(/\s+/g, " ").trim();
  if (n.length < NAME_MIN || n.length > NAME_MAX) return null;
  return n;
}

/** A cell starting with = + - @ would run as a formula in Sheets: prefix it so it stays text. */
function sheetSafe(text) {
  return /^[=+\-@]/.test(text) ? "'" + text : text;
}

/** Workshop codes are generated by us: 6 chars from an unambiguous alphabet. */
var CODE_ALPHABET = "abcdefghjkmnpqrstuvwxyz23456789";
function isValidWorkshopCode(code) {
  return typeof code === "string" && /^[a-hjkmnp-z2-9]{6}$/.test(code);
}
function newWorkshopCode(randomFn) {
  var c = "";
  for (var i = 0; i < 6; i++) c += CODE_ALPHABET.charAt(Math.floor(randomFn() * CODE_ALPHABET.length));
  return c;
}

/** Flags for the moderator, never a rejection: fast finishers and same-spot tappers. */
function suspicionFlags(answers, seconds, displayOrder) {
  var flags = [];
  if (typeof seconds === "number" && seconds > 0 && seconds < MIN_SECONDS_PLAUSIBLE) flags.push("fast");
  if (displayOrder && displayOrder.length === answers.length) {
    // position on screen of the first choice in every row; same spot on all 20 rows = suspicious
    var firstPos = answers.map(function (row, i) { return displayOrder[i].indexOf(row[0]); });
    if (firstPos.every(function (p) { return p === firstPos[0]; })) flags.push("same-spot");
  }
  return flags;
}

/**
 * Validate a submission payload. Returns {ok:true, value:{...}} or {ok:false, error:"code"}.
 * workshop: the row from the Workshops tab (or null if the code is unknown).
 */
function validateSubmission(payload, workshop, rowsSoFar) {
  if (!payload || typeof payload !== "object") return { ok: false, error: "bad_request" };
  if (!isValidWorkshopCode(payload.workshop)) return { ok: false, error: "bad_workshop" };
  if (!workshop) return { ok: false, error: "unknown_workshop" };
  if (!workshop.open) return { ok: false, error: "workshop_closed" };
  if (rowsSoFar >= MAX_ROWS_PER_WORKSHOP) return { ok: false, error: "workshop_full" };
  var name = cleanName(payload.name);
  if (!name) return { ok: false, error: "bad_name" };
  if (!isValidAnswers(payload.answers)) return { ok: false, error: "bad_answers" };
  var s = scoreAnswers(payload.answers);           // always recomputed here, client totals are ignored
  var seconds = typeof payload.seconds === "number" ? Math.round(payload.seconds) : null;
  return {
    ok: true,
    value: {
      name: name, scores: s, code: codeOf(s), answers: payload.answers, seconds: seconds,
      flags: suspicionFlags(payload.answers, seconds, payload.displayOrder)
    }
  };
}

/* ---------------- moderator ---------------- */

var MAX_ROSTER = 200;
var KEY_RE = /^[0-9a-f]{32}$/;

function isWellFormedKey(k) { return typeof k === "string" && KEY_RE.test(k); }

/** Compare without stopping at the first different character (no timing hint about the key). */
function keysMatch(given, stored) {
  if (!isWellFormedKey(given) || !isWellFormedKey(stored)) return false;
  var diff = 0;
  for (var i = 0; i < stored.length; i++) diff |= given.charCodeAt(i) ^ stored.charCodeAt(i);
  return diff === 0;
}

/** Expected-names list from the moderator page: cleaned, de-duplicated, capped. null if not a list. */
function cleanRoster(list) {
  if (!Array.isArray(list)) return null;
  var out = [], seen = {};
  for (var i = 0; i < list.length && out.length < MAX_ROSTER; i++) {
    var n = cleanName(list[i]);
    if (n && !seen[n]) { seen[n] = true; out.push(n); }
  }
  return out;
}

/** Sheet row (array, header order) → result row for the moderator page. */
function submissionFromRow(r, tz, fmt) {
  return {
    name: String(r[2]).replace(/^'/, ""), P: Number(r[3]), A: Number(r[4]), E: Number(r[5]), I: Number(r[6]),
    code: String(r[7]).replace(/^'/, ""), t: fmt(r[0], tz), seconds: r[8] === "" ? null : Number(r[8]),
    flags: String(r[9] || "").split(" ").filter(String)
  };
}

